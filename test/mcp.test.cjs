'use strict';
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const os = require('node:os');
const { spawn } = require('node:child_process');
const readline = require('node:readline');
const { init } = require('../lib/config.cjs');
const fixture = require('../examples/event.json');
test('MCP subprocess handshake, tools, source validation and candidate separation', { timeout: 15000 }, async t => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'ima-memory-mcp-test-')); init(root);
  const child = spawn(process.execPath, [path.resolve(__dirname, '..', 'bin', 'ima-agent-memory.cjs'), 'serve', '--home', root], { stdio: ['pipe', 'pipe', 'pipe'], windowsHide: true });
  const exited = new Promise(resolve => child.on('exit', resolve));
  t.after(async () => { child.stdin.end(); child.kill(); await exited; assert.ok(path.basename(root).startsWith('ima-memory-mcp-test-')); fs.rmSync(root, { recursive: true, force: true }); });
  let id = 0, stderr = ''; const pending = new Map();
  child.stderr.on('data', b => { stderr += b; });
  readline.createInterface({ input: child.stdout }).on('line', line => { const r = JSON.parse(line); pending.get(r.id)?.(r); pending.delete(r.id); });
  const request = (method, params) => new Promise(resolve => { const key = ++id; pending.set(key, resolve); child.stdin.write(JSON.stringify({ jsonrpc: '2.0', id: key, method, params }) + '\n'); });
  const call = (name, args) => request('tools/call', { name, arguments: args });
  let r = await request('initialize', { protocolVersion: '2025-11-25', capabilities: {}, clientInfo: { name: 'synthetic-test', version: '1' } });
  assert.equal(r.result.protocolVersion, '2025-11-25');
  r = await request('tools/list', {}); assert.equal(r.result.tools.length, 4);
  r = await call('memory_search', { query: 'test' }); assert.equal(r.result.isError, true);
  r = await call('memory_record_event', { ...fixture, source: '' }); assert.equal(r.result.isError, true);
  r = await call('memory_record_event', fixture); assert.equal(JSON.parse(r.result.content[0].text).accepted_as_candidate, true);
  r = await call('memory_search', { query: 'two languages', project: 'demo' }); assert.equal(JSON.parse(r.result.content[0].text).results.length, 0);
  r = await call('memory_search', { query: 'two languages', project: 'demo', include_candidates: true }); assert.equal(JSON.parse(r.result.content[0].text).results.length, 1);
  r = await call('memory_read', { document: '../config.json' }); assert.equal(r.result.isError, true);
  r = await call('memory_search', { query: 'test', project: 'demo', include_candidates: 'true' }); assert.equal(r.result.isError, true);
  r = await call('memory_current', { project: 'demo', extra: true }); assert.equal(r.result.isError, true);
  r = await call('memory_current', { project: 'demo' }); assert.ok(JSON.parse(r.result.content[0].text).documents['curated/projects/demo.md']);
  assert.equal(stderr, '');
});
